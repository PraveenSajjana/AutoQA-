import { TestCase, TestRun, TestStep } from '../types/qa';

/**
 * Compiles JSON Test Cases into standard runnable Playwright TypeScript code
 */
export function compileToPlaywrightTS(testCases: TestCase[], baseUrl = 'http://localhost:3000'): string {
  const codeLines: string[] = [
    `import { test, expect } from '@playwright/test';`,
    ``,
    `/**`,
    ` * Generated by AutoQA Studio Test Orchestrator`,
    ` * Target Base URL: ${baseUrl}`,
    ` * Total Test Cases: ${testCases.length}`,
    ` */`,
    ``,
    `test.describe('Automated QA Test Suite', () => {`,
    `  test.beforeEach(async ({ page }) => {`,
    `    // Configure default timeouts & viewport`,
    `    page.setDefaultTimeout(8000);`,
    `    await page.setViewportSize({ width: 1280, height: 800 });`,
    `  });`,
    ``,
  ];

  for (const tc of testCases) {
    codeLines.push(`  /**`);
    codeLines.push(`   * Test ID: ${tc.test_id}`);
    if (tc.feature_id) {
      codeLines.push(`   * Feature ID: ${tc.feature_id}`);
    }
    if (tc.objective) {
      codeLines.push(`   * Objective: ${tc.objective}`);
    }
    codeLines.push(`   * Type: ${(tc.test_type || tc.category || 'functional').toUpperCase()}`);
    codeLines.push(`   * Requirement: ${tc.requirement_id || 'N/A'}`);
    if (tc.traceability) {
      codeLines.push(`   * Traceability: ${tc.traceability}`);
    }
    codeLines.push(`   * Priority: ${tc.priority.toUpperCase()}`);
    if (tc.confidence) {
      codeLines.push(`   * Discovery Confidence: ${tc.confidence}%`);
    }
    if (tc.preconditions.length > 0) {
      codeLines.push(`   * Preconditions: ${tc.preconditions.join('; ')}`);
    }
    codeLines.push(`   */`);
    codeLines.push(`  test('${escapeString(tc.test_id)}: ${escapeString(tc.title)}', async ({ page }) => {`);

    for (let i = 0; i < tc.steps.length; i++) {
      const step = tc.steps[i];
      const stepComment = step.description ? `    // Step ${i + 1}: ${step.description}` : `    // Step ${i + 1}: ${step.action} on ${step.target}`;
      codeLines.push(stepComment);
      const code = generateStepPlaywrightCode(step, baseUrl);
      codeLines.push(`    ${code}`);
    }

    codeLines.push(`  });`);
    codeLines.push(``);
  }

  codeLines.push(`});`);
  return codeLines.join('\n');
}

function generateStepPlaywrightCode(step: TestStep, baseUrl: string): string {
  const target = step.target;
  const val = step.value ? escapeString(step.value) : '';

  switch (step.action) {
    case 'navigate': {
      const url = target.startsWith('http') ? target : `${baseUrl}${target.startsWith('/') ? '' : '/'}${target}`;
      return `await page.goto('${escapeString(url)}');`;
    }
    case 'fill': {
      return `await page.locator('${escapeSelector(target)}').fill('${val}');`;
    }
    case 'click': {
      return `await page.locator('${escapeSelector(target)}').click();`;
    }
    case 'select': {
      return `await page.locator('${escapeSelector(target)}').selectOption('${val}');`;
    }
    case 'assert_visible': {
      return `await expect(page.locator('${escapeSelector(target)}')).toBeVisible({ timeout: ${step.timeoutMs || 5000} });`;
    }
    case 'assert_text': {
      return `await expect(page.locator('${escapeSelector(target)}')).toContainText('${val}');`;
    }
    case 'assert_value': {
      return `await expect(page.locator('${escapeSelector(target)}')).toHaveValue('${val}');`;
    }
    case 'wait': {
      const duration = parseInt(val, 10) || step.timeoutMs || 1000;
      return `await page.waitForTimeout(${duration});`;
    }
    case 'screenshot': {
      const filename = val || `screenshot-${Date.now()}.png`;
      return `await page.screenshot({ path: 'evidence/${filename}', fullPage: true });`;
    }
    default:
      return `// Unsupported action: ${(step as any).action}`;
  }
}

function escapeSelector(selector: string): string {
  // If selector is a bare id or name, format nicely or keep as locator
  if (!selector.startsWith('#') && !selector.startsWith('.') && !selector.startsWith('[') && !selector.includes(' ')) {
    // Try data-testid or id or input name
    return `[data-testid="${selector}"], #${selector}, [name="${selector}"]`;
  }
  return selector.replace(/'/g, "\\'");
}

function escapeString(str: string): string {
  return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

/**
 * Compiles a completed TestRun into standard JUnit XML format
 */
export function compileToJUnitXML(run: TestRun): string {
  const timestamp = new Date(run.startedAt).toISOString();
  const timeSec = (run.durationMs / 1000).toFixed(3);

  const xmlLines: string[] = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<testsuites name="AutoQA Test Suite" tests="${run.totalTests}" failures="${run.failedCount}" errors="0" skipped="${run.skippedCount}" time="${timeSec}">`,
    `  <testsuite name="${run.projectName}" tests="${run.totalTests}" failures="${run.failedCount}" errors="0" skipped="${run.skippedCount}" time="${timeSec}" timestamp="${timestamp}">`,
  ];

  for (const result of run.results) {
    const testTime = (result.durationMs / 1000).toFixed(3);
    xmlLines.push(`    <testcase classname="${run.projectName}" name="${escapeXml(result.testId)} - ${escapeXml(result.testTitle)}" time="${testTime}">`);

    if (result.status === 'failed') {
      const defect = result.defect;
      const failureMsg = defect ? `[${defect.category}] ${defect.actualBehavior}` : 'Step assertion failure';
      const failureDetails = defect
        ? `Root Cause: ${defect.rootCauseAnalysis}\nSuggested Fix: ${defect.suggestedFix}\n\nExecution Logs:\n${result.logs.join('\n')}`
        : result.logs.join('\n');

      xmlLines.push(`      <failure message="${escapeXml(failureMsg)}" type="${defect?.category || 'AssertionError'}">`);
      xmlLines.push(escapeXml(failureDetails));
      xmlLines.push(`      </failure>`);
    } else if (result.status === 'skipped') {
      xmlLines.push(`      <skipped message="Test was skipped"/>`);
    }

    xmlLines.push(`    </testcase>`);
  }

  xmlLines.push(`  </testsuite>`);
  xmlLines.push(`</testsuites>`);
  return xmlLines.join('\n');
}

function escapeXml(unsafe: string): string {
  return unsafe
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/**
 * Generates CSV / Excel spreadsheet content
 */
export function compileToCSV(testCases: TestCase[], run?: TestRun): string {
  const headers = [
    'Test ID',
    'Feature ID',
    'Test Type',
    'Requirement ID',
    'Title',
    'Objective',
    'Traceability',
    'Priority',
    'Status',
    'Execution Result',
    'Duration (ms)',
    'Steps Count',
    'Preconditions',
    'Expected Result',
    'Failure Category',
    'Root Cause / Notes'
  ];

  const rows: string[] = [headers.join(',')];

  for (const tc of testCases) {
    const result = run?.results.find((r) => r.testId === tc.test_id);
    const execStatus = result ? result.status.toUpperCase() : 'NOT_RUN';
    const duration = result ? result.durationMs.toString() : '-';
    const failureCategory = result?.defect?.category || '-';
    const rca = result?.defect ? result.defect.rootCauseAnalysis.replace(/\n/g, ' ') : (tc.reviewNotes || '-');

    const values = [
      tc.test_id,
      tc.feature_id || 'N/A',
      tc.test_type || tc.category || 'functional',
      tc.requirement_id || 'N/A',
      tc.title,
      tc.objective || 'N/A',
      tc.traceability || 'N/A',
      tc.priority,
      tc.status,
      execStatus,
      duration,
      tc.steps.length.toString(),
      tc.preconditions.join('; '),
      tc.expected_result,
      failureCategory,
      rca
    ].map((val) => `"${val.replace(/"/g, '""')}"`);

    rows.push(values.join(','));
  }

  return rows.join('\n');
}

